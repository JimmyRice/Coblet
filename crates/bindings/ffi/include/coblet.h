// {"id","method","state","player","session_expires_at","license",
// "license_checked_at","owns_game","data"}]}`.
//
// `default` is the default account's ID or null. `state` is `ready`,
// `needs-refresh`, `needs-reauth`, `no-license` or `no-profile`. `player`
